import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const origin=process.env.ROADLINK_PREVIEW_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch();
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[],workers=[];
  page.on('pageerror',error=>errors.push(error.message));page.on('worker',worker=>workers.push(worker.url()));
  await page.goto(origin,{waitUntil:'domcontentloaded'});
  await page.locator('.map-canvas[data-map-ready="true"]').waitFor({timeout:30000});
  await page.getByRole('textbox',{name:'Tìm địa điểm',exact:true}).fill('21.0283334,105.854041');
  await page.getByRole('button',{name:'Tìm kiếm',exact:true}).click();
  await page.locator('.place-result').filter({hasText:'Tọa độ đã nhập'}).click();
  await page.getByRole('button',{name:'Chuyển bản đồ 3D',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('.map-canvas')?.getAttribute('data-map-pitch'))>45&&Number(document.querySelector('.map-canvas')?.getAttribute('data-visible-buildings'))>0,{},{timeout:60000});
  const buildings=Number(await page.locator('.map-canvas').getAttribute('data-visible-buildings'));
  await mkdir('docs/screenshots',{recursive:true});await page.screenshot({path:'docs/screenshots/production-hanoi-3d.png'});
  await page.getByRole('button',{name:'Chỉ đường',exact:true}).click();
  await page.getByRole('button',{name:'Đổi điểm đi',exact:true}).click();
  await page.getByRole('textbox',{name:'Tìm điểm đi',exact:true}).fill('20.4057073,106.5031738');
  await page.getByRole('button',{name:'Tìm kiếm',exact:true}).click();
  await page.locator('.place-result').filter({hasText:'Tọa độ đã nhập'}).click();
  await page.getByText('Tuyến đề xuất',{exact:true}).waitFor({timeout:30000});
  await page.getByRole('button',{name:'Mở dữ liệu đường',exact:true}).click();
  await page.locator('[data-road-scope="route"][data-scan-complete="true"]').waitFor({timeout:60000});
  const points=Number(await page.getByRole('heading',{name:/Điểm gần tuyến đang hiển thị/}).locator('span').innerText());
  const pitch=Number(await page.locator('.map-canvas').getAttribute('data-map-pitch'));
  if(points<1||pitch<45||errors.length||!workers.some(url=>url.includes('/assets/maplibre-gl-worker-')))throw new Error(JSON.stringify({points,pitch,errors,workers}));
  await page.screenshot({path:'docs/screenshots/production-tien-hai-hanoi-full-route.png'});
  if(errors.length)throw new Error(JSON.stringify(errors));
  const report={checkedAt:new Date().toISOString(),servedBuild:'dist through Vite preview',replacedAPIs:0,suppliedDevicePosition:false,renderedHanoiBuildingFeatures:buildings,tienHaiHanoiWholeRoutePoints:points,pitchAfterRouteSelection:pitch,workers,errors};
  await writeFile('docs/PRODUCTION_MAP_REPORT.json',JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
}finally{await browser.close();}
